"""Brevo transactional email for outreach (https://developers.brevo.com/docs/send-a-transactional-email).

One message per call. Brevo accepts one body type per request, so only the HTML body is sent; the plain-text
version is generated by Brevo. ``email_payload`` is pure so the request shape is unit-tested without a network.
"""

from __future__ import annotations

BREVO_SEND_URL = "https://api.brevo.com/v3/smtp/email"
TAG = "reckon_sales_agent"


def email_payload(to: str, sender_email: str, sender_name: str, subject: str, html: str, message_name: str) -> dict:
    """The JSON body for POST /v3/smtp/email. ``tags`` carry the outreach id so Brevo events can be traced back."""
    return {
        "sender": {"name": sender_name, "email": sender_email},
        "to": [{"email": to}],
        "subject": subject,
        "htmlContent": html,
        "tags": [TAG, message_name],
    }


def send_email(message, settings) -> str | None:
    """Send one outreach email through Brevo; returns Brevo's messageId."""
    import requests

    from reckon_sales_agent.providers.channels import ChannelUnavailable
    from reckon_sales_agent.providers.llm import http_reason

    key = settings.get_password("brevo_api_key", raise_exception=False) if settings.get("brevo_api_key") else ""
    if not key or not settings.get("brevo_sender_email"):
        raise ChannelUnavailable("Enter the Brevo API key and a sender email verified in Brevo in Sales Agent Settings.")
    payload = email_payload(message.recipient, settings.brevo_sender_email, settings.sender_name or message.company,
                            message.subject or "", message.body or "", message.name)
    try:
        response = requests.post(BREVO_SEND_URL, json=payload, timeout=30,
                                 headers={"api-key": key, "accept": "application/json"})
    except requests.RequestException as exc:
        raise ChannelUnavailable("Brevo unreachable.") from exc
    if response.status_code >= 400:
        raise ChannelUnavailable(f"Brevo refused the email: {http_reason(response)}")
    return (response.json() or {}).get("messageId")


# Brevo event → the shape ``agents.engagement.normalize_email_events`` reads. Other events (opened, clicked,
# deferred, request, ...) carry no action for a campaign, so they are ignored.
EVENT_MAP = {
    "delivered": ("delivered", ""),
    "hard_bounce": ("bounce", "hard"),
    "invalid_email": ("bounce", "hard"),
    "blocked": ("bounce", "hard"),
    "soft_bounce": ("bounce", "soft"),
    "spam": ("spamreport", ""),
    "unsubscribed": ("unsubscribe", ""),
}


def normalize_events(items) -> list[dict]:
    """Brevo webhook events: one JSON object per call, or a list. The id combines the message, the event and its time,
    because Brevo's own ``id`` is the webhook's id and repeats across events."""
    out = []
    for item in items if isinstance(items, list) else [items]:
        if not isinstance(item, dict):
            continue
        kind, bounce = EVENT_MAP.get(str(item.get("event") or ""), ("", ""))
        message = str(item.get("message-id") or "").strip()
        if not kind or not message:
            continue
        stamp = str(item.get("ts_epoch") or item.get("ts_event") or item.get("date") or "")
        out.append({"id": f"brevo:{message}:{item['event']}:{stamp}", "type": kind, "bounce_type": bounce or "hard",
                    "email": item.get("email") or "", "message": message})
    return out
